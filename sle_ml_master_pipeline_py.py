# 5. CLINICAL CORRELATION
# ==========================================
def plot_clinical_correlation(df, features):
    print("\n--- 4. Generating Clinical Correlation Heatmap ---")
    corr_df = df[features + ['BILAG Score']]
    correlations = corr_df.corr(method='pearson')[['BILAG Score']].drop('BILAG Score')
    correlations = correlations.sort_values(by='BILAG Score', ascending=False)

    plt.figure(figsize=(4, 5))
    sns.heatmap(correlations, annot=True, cmap='vlag', center=0, fmt='.2f', cbar_kws={'label': 'Pearson r'})
    plt.title('Fig ML_2: Correlation with\nEasy-BILAG Score', fontweight='bold')
    plt.tight_layout()
    plt.savefig('Fig_ML_2_Correlation.png', dpi=300)
    plt.close()

