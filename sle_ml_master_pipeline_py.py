# ==========================================
if __name__ == "__main__":
    print("Starting SLE Machine Learning Pipeline...")

    # 1. Load Data
    df, X_scaled, y, features = load_and_preprocess_data()

    # 2. Train & Evaluate
    y_true, y_prob = run_loocv_evaluation(X_scaled, y)

    # 3. Robustness Tests
    run_robustness_checks(X_scaled, y)

    # 4. Generate All ML Visualizations
    generate_visualizations(df, X_scaled, y, features, y_true, y_prob)

    # 5. Generate Clinical Correlations
    plot_clinical_correlation(df, features)

    print("\n✅ Pipeline successfully completed! All figures saved as PNG files in the current directory.")